import {
  DEFAULT_CV,
  EMPTY_EDUCATION,
  EMPTY_EXPERIENCE,
  type CvData,
  type CvTemplateId,
  type SampleCvMeta,
} from "./types";

function exp(
  title: string,
  company: string,
  location: string,
  start: string,
  end: string,
  current: boolean,
  bullets: string[]
) {
  return {
    ...EMPTY_EXPERIENCE(),
    title,
    company,
    location,
    start,
    end,
    current,
    bullets: bullets.join("\n"),
  };
}

function edu(school: string, degree: string, field: string, end: string) {
  return { ...EMPTY_EDUCATION(), school, degree, field, end };
}

type Spec = {
  profession: string;
  category: string;
  template: CvTemplateId;
  blurb: string;
  summary: string;
  skills: string;
  certifications?: string;
  languages?: string;
  experience: ReturnType<typeof exp>[];
  education: ReturnType<typeof edu>[];
  name?: string;
  location?: string;
};

function build(s: Spec): { meta: SampleCvMeta; data: CvData } {
  const base = s.profession
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
  const cat = s.category
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 24);
  const id = `${base}--${cat}`;
  return {
    meta: {
      id,
      profession: s.profession,
      category: s.category,
      template: s.template,
      blurb: s.blurb,
    },
    data: {
      ...DEFAULT_CV(),
      fullName: s.name || "Alex Candidate",
      title: s.profession,
      email: "candidate@email.com",
      phone: "+966 50 000 0000",
      location: s.location || "Saudi Arabia / GCC",
      summary: s.summary,
      skills: s.skills,
      certifications: s.certifications || "",
      languages: s.languages || "English",
      experience: s.experience,
      education: s.education,
      template: s.template,
    },
  };
}

